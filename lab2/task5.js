// Дано целое число. Для нуля вывести «нулевое число», для остальных чисел описать знак и чётность, например «отрицательное четное число».
const n = Number(process.argv[2]);

if (n === 0) {
    console.log("нулевое число");
} else {
    const sign = n > 0 ? "положительное" : "отрицательное";
    const parity = n % 2 === 0 ? "четное" : "нечетное";
    console.log(sign, parity, "число");
}
