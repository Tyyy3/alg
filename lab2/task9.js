// Дано целое число от 100 до 999. Записать его словами, например для 256 вывести «двести пятьдесят шесть».
const n = Number(process.argv[2]);
const hundreds = [
    "", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
    "семьсот", "восемьсот", "девятьсот"
];
const tens = [
    "", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
    "семьдесят", "восемьдесят", "девяносто"
];
const teens = [
    "десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
    "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"
];
const units = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"];

let result = hundreds[Math.floor(n / 100)];
const rest = n % 100;
if (rest >= 10 && rest < 20) {
    result += " " + teens[rest - 10];
} else {
    if (rest >= 20) {
        result += " " + tens[Math.floor(rest / 10)];
    }
    if (rest % 10 !== 0) {
        result += " " + units[rest % 10];
    }
}

console.log(result);
